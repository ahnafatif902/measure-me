/* Downloads the Google Fonts used by the app (Fraunces + Outfit, the same
   families/weights as the reference build) into src/assets/fonts and writes
   src/fonts.css with local urls.

   Run: node scripts/download-fonts.mjs */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "src", "assets", "fonts");
const cssPath = path.join(root, "src", "fonts.css");
const cssUrl =
  "https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,560;9..144,650&family=Outfit:wght@400;500;600&display=swap";
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/138.0.0.0 Safari/537.36";

const res = await fetch(cssUrl, { headers: { "User-Agent": UA } });
if (!res.ok) throw new Error(`fonts css: ${res.status}`);
let css = await res.text();

fs.mkdirSync(outDir, { recursive: true });

const urls = [...new Set([...css.matchAll(/url\((https:[^)]+)\)/g)].map((m) => m[1]))];
console.log(`font files to download: ${urls.length}`);

const map = new Map();
let i = 0;
for (const url of urls) {
  const name = `font-${i++}.woff2`;
  const file = await fetch(url, { headers: { "User-Agent": UA } });
  if (!file.ok) throw new Error(`${url}: ${file.status}`);
  const buf = Buffer.from(await file.arrayBuffer());
  fs.writeFileSync(path.join(outDir, name), buf);
  map.set(url, name);
  console.log(`  ${name}  ${String(buf.length).padStart(7)} B  ${url.split("/").pop()}`);
}

css = css.replace(/url\((https:[^)]+)\)/g, (_, url) => `url("./assets/fonts/${map.get(url)}")`);
const header =
  "/* Fraunces (display) + Outfit (UI), self-hosted — generated by scripts/download-fonts.mjs.\n" +
  "   Same families/weights as the reference build; keeps the app fully offline. */\n\n";
fs.writeFileSync(cssPath, header + css.trim() + "\n");
console.log("wrote", path.relative(root, cssPath));
